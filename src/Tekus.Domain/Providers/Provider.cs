using System.Text.RegularExpressions;
using Tekus.Domain.Common;
using Tekus.Domain.Providers.Events;

namespace Tekus.Domain.Providers;

/// <summary>
/// Provider aggregate root.
/// <para>
/// A provider is the consistency boundary for everything that describes the legal entity, its
/// user defined custom fields and the set of services it offers. Services themselves are a
/// separate aggregate (a service catalogue) referenced by id, never by object graph, so two
/// providers can safely offer the same service without sharing a mutable instance.
/// </para>
/// </summary>
public sealed partial class Provider : AggregateRoot
{
    public const int NitMaxLength = 20;
    public const int NameMaxLength = 150;
    public const int EmailMaxLength = 200;
    public const int MaxCustomFields = 50;
    public const int MaxServicesPerProvider = 200;

    public const string EmailPattern = Common.EmailAddress.Pattern;
    public const string NitPattern = @"^\d{5,20}(-\d)?$";
    public const string CustomFieldKeyPattern = @"^[\p{L}\p{N}][\p{L}\p{N} _.,\-()/&+']*$";

    private readonly List<ProviderCustomField> _customFields = [];
    private readonly List<ProviderService> _offeredServices = [];

    /// <summary>Required by EF Core.</summary>
    private Provider()
    {
    }

    private Provider(Guid id, string nit, string name, string email, DateTime utcNow)
        : base(id)
    {
        Nit = nit;
        Name = name;
        Email = email;
        IsActive = true;
        CreatedAtUtc = utcNow;
        UpdatedAtUtc = utcNow;
        Version = 1;

        RaiseDomainEvent(new ProviderCreatedDomainEvent(Id, Nit, Name, utcNow));
    }

    public string Nit { get; private set; } = string.Empty;

    public string Name { get; private set; } = string.Empty;

    public string Email { get; private set; } = string.Empty;

    public bool IsActive { get; private set; }

    public DateTime CreatedAtUtc { get; private set; }

    public DateTime? UpdatedAtUtc { get; private set; }

    /// <summary>
    /// Optimistic concurrency token incremented on every change. A portable alternative to
    /// SQL Server's <c>rowversion</c> that also works with SQLite (used by the test suite).
    /// </summary>
    public long Version { get; private set; }

    /// <summary>User defined fields ("Número de contacto en marte", ...).</summary>
    public IReadOnlyCollection<ProviderCustomField> CustomFields => _customFields.AsReadOnly();

    public IReadOnlyCollection<ProviderService> OfferedServices => _offeredServices.AsReadOnly();

    /// <summary>Creates a new, valid provider. The identifier is generated by the domain.</summary>
    public static Provider Create(string? nit, string? name, string? email, DateTime utcNow)
        => new(Guid.NewGuid(), NormalizeNit(nit), NormalizeName(name), NormalizeEmail(email), utcNow);

    public void Update(string? nit, string? name, string? email, DateTime utcNow)
    {
        Nit = NormalizeNit(nit);
        Name = NormalizeName(name);
        Email = NormalizeEmail(email);

        Touch(utcNow);
        RaiseDomainEvent(new ProviderUpdatedDomainEvent(Id, Nit, Name, utcNow));
    }

    public void Activate(DateTime utcNow)
    {
        if (IsActive)
        {
            return;
        }

        IsActive = true;
        Touch(utcNow);
    }

    /// <summary>
    /// Logical delete. Providers are never physically removed because their offerings are part of
    /// the historical reporting; deleting them would also break the "services per country" figures.
    /// </summary>
    public void Deactivate(DateTime utcNow)
    {
        if (!IsActive)
        {
            return;
        }

        IsActive = false;
        Touch(utcNow);
        RaiseDomainEvent(new ProviderUpdatedDomainEvent(Id, Nit, Name, utcNow));
    }

    /// <summary>Creates or updates a custom field, matched by key (case-insensitive).</summary>
    public ProviderCustomField UpsertCustomField(string? key, string? value, DateTime utcNow)
    {
        var normalizedKey = NormalizeCustomFieldKey(key);
        var normalizedValue = ProviderCustomField.NormalizeValue(value, normalizedKey);

        var existing = _customFields.FirstOrDefault(
            field => string.Equals(field.Key, normalizedKey, StringComparison.OrdinalIgnoreCase));

        ProviderCustomField target;

        if (existing is null)
        {
            if (_customFields.Count >= MaxCustomFields)
            {
                throw new DomainException(
                    $"A provider cannot define more than {MaxCustomFields} custom fields.",
                    ErrorCodes.Validation);
            }

            target = ProviderCustomField.Create(Id, normalizedKey, normalizedValue, utcNow);
            _customFields.Add(target);
        }
        else
        {
            existing.UpdateValue(normalizedValue, utcNow);
            target = existing;
        }

        Touch(utcNow);
        RaiseDomainEvent(new ProviderCustomFieldChangedDomainEvent(Id, target.Key, utcNow));

        return target;
    }

    public void RemoveCustomField(string? key, DateTime utcNow)
    {
        var normalizedKey = NormalizeCustomFieldKey(key);

        var existing = _customFields.FirstOrDefault(
            field => string.Equals(field.Key, normalizedKey, StringComparison.OrdinalIgnoreCase));

        if (existing is null)
        {
            throw new DomainException(
                $"The provider does not define a custom field named '{normalizedKey}'.",
                ErrorCodes.NotFound);
        }

        _customFields.Remove(existing);
        Touch(utcNow);
        RaiseDomainEvent(new ProviderCustomFieldChangedDomainEvent(Id, normalizedKey, utcNow));
    }

    /// <summary>Links a service of the catalogue to this provider. Idempotent.</summary>
    public void AssignService(Guid serviceId, DateTime utcNow)
    {
        Guard.NotEmpty(serviceId, nameof(serviceId));

        if (_offeredServices.Any(offering => offering.ServiceId == serviceId))
        {
            return;
        }

        if (_offeredServices.Count >= MaxServicesPerProvider)
        {
            throw new DomainException(
                $"A provider cannot offer more than {MaxServicesPerProvider} services.",
                ErrorCodes.Validation);
        }

        _offeredServices.Add(ProviderService.Assign(Id, serviceId, utcNow));
        Touch(utcNow);
        RaiseDomainEvent(new ProviderServiceAssignedDomainEvent(Id, serviceId, utcNow));
    }

    /// <summary>Unlinks a service from this provider. Idempotent.</summary>
    public void RemoveService(Guid serviceId, DateTime utcNow)
    {
        Guard.NotEmpty(serviceId, nameof(serviceId));

        var existing = _offeredServices.FirstOrDefault(offering => offering.ServiceId == serviceId);

        if (existing is null)
        {
            return;
        }

        _offeredServices.Remove(existing);
        Touch(utcNow);
        RaiseDomainEvent(new ProviderServiceRemovedDomainEvent(Id, serviceId, utcNow));
    }

    /// <summary>Replaces the whole set of offered services in one operation (used by PUT).</summary>
    public void ReplaceServices(IEnumerable<Guid> serviceIds, DateTime utcNow)
    {
        ArgumentNullException.ThrowIfNull(serviceIds);

        var targetIds = serviceIds
            .Where(id => id != Guid.Empty)
            .Distinct()
            .ToHashSet();

        var currentIds = _offeredServices
            .Select(offering => offering.ServiceId)
            .ToHashSet();

        var hasChanges = false;

        // Remove offerings that are no longer in the target set.
        foreach (var serviceId in currentIds.Except(targetIds).ToArray())
        {
            var existing = _offeredServices.FirstOrDefault(offering => offering.ServiceId == serviceId);

            if (existing is not null)
            {
                _offeredServices.Remove(existing);
                hasChanges = true;
            }
        }

        // Add offerings that are missing from the current set.
        foreach (var serviceId in targetIds.Except(currentIds).ToArray())
        {
            if (_offeredServices.Count >= MaxServicesPerProvider)
            {
                throw new DomainException(
                    $"A provider cannot offer more than {MaxServicesPerProvider} services.",
                    ErrorCodes.Validation);
            }

            _offeredServices.Add(ProviderService.Assign(Id, serviceId, utcNow));
            hasChanges = true;
        }

        if (hasChanges)
        {
            Touch(utcNow);
        }
    }

    private void Touch(DateTime utcNow)
    {
        UpdatedAtUtc = utcNow;
        Version++;
    }

    /// <summary>Normalises and validates a NIT (strips dots/spaces, keeps the optional check digit).</summary>
    public static string NormalizeNit(string? nit)
    {
        var normalized = Guard
            .NotNullOrWhiteSpace(nit, "nit", NitMaxLength)
            .Replace(".", string.Empty, StringComparison.Ordinal)
            .Replace(" ", string.Empty, StringComparison.Ordinal);

        return NitRegex().IsMatch(normalized)
            ? normalized
            : throw new DomainException(
                $"'{nit}' is not a valid NIT. Expected 5 to 20 digits with an optional check digit (e.g. 900123456-7).",
                ErrorCodes.Validation);
    }

    /// <summary>Normalises and validates the provider name.</summary>
    public static string NormalizeName(string? name)
        => Guard.NotNullOrWhiteSpace(name, "name", NameMaxLength, minLength: 3);

    /// <summary>Normalises and validates the contact e-mail of the provider.</summary>
    public static string NormalizeEmail(string? email) => EmailAddress.Create(email).Value;

    /// <summary>Normalises and validates the name of a user defined field.</summary>
    public static string NormalizeCustomFieldKey(string? key)
    {
        var normalized = Guard.NotNullOrWhiteSpace(key, "key", ProviderCustomField.KeyMaxLength, minLength: 2)
            .SquashInnerSpaces();

        return CustomFieldKeyRegex().IsMatch(normalized)
            ? normalized
            : throw new DomainException(
                $"'{key}' is not a valid custom field name. Use letters, digits, spaces and _.,-()/&+ only.",
                ErrorCodes.Validation);
    }

    [GeneratedRegex(NitPattern, RegexOptions.CultureInvariant)]
    private static partial Regex NitRegex();

    [GeneratedRegex(CustomFieldKeyPattern, RegexOptions.CultureInvariant)]
    private static partial Regex CustomFieldKeyRegex();
}
